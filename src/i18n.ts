function languageOf(hass: any): string {
  return String(hass?.locale?.language || hass?.language || navigator.language || "en").toLowerCase();
}

export function t(hass: any, key: TranslationKey, vars: Record<string, string | number | null | undefined> = {}): string {
  const dict = languageOf(hass).startsWith("ru") ? RU : EN;
  let value = dict[key] || EN[key];
  for (const [name, replacement] of Object.entries(vars)) {
    value = value.split(`{${name}}`).join(String(replacement ?? ""));
  }
  return value;
}

export function localizeUnit(hass: any, unit: string): string {
  if (!languageOf(hass).startsWith("ru")) return unit;
  const normalized = String(unit).toLowerCase();
  if (["s", "sec", "seconds"].includes(normalized)) return "с";
  if (["min", "m", "minutes"].includes(normalized)) return "мин";
  if (["h", "hr", "hours"].includes(normalized)) return "ч";
  if (["d", "day", "days"].includes(normalized)) return "д";
  return unit;
}
